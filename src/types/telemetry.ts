/**
 * UTM MONITORING SYSTEM - DATA CONTRACTS & SCHEMAS (VERSION 1.0)
 * Standards: WGS84 (EPSG:4326), Altitude in Meters MSL/AGL, Metric SI Units (m/s, km, deg)
 */

export const SCHEMA_VERSION = '1.0' as const;

export type AltitudeReference = 'MSL' | 'AGL' | 'WGS84';

export type UAVFlightStatus = 
  | 'IDLE' 
  | 'PREFLIGHT' 
  | 'TAKEOFF' 
  | 'FLYING' 
  | 'HOVER' 
  | 'LANDING' 
  | 'EMERGENCY' 
  | 'LOST_LINK' 
  | 'COMPLETED'
  | 'UNKNOWN';

export type UAVType = 'MULTIROTOR' | 'FIXED_WING' | 'VTOL';

/**
 * UAV Technical & Physical Performance Profile (Part 1 / Part 3 metadata)
 */
export interface UAVPerformanceProfile {
  uav_type: UAVType;
  model_name: string;
  manufacturer?: string;
  dimensions_m: {
    length: number;
    wingspan_or_diameter: number;
    height: number;
  };
  mtow_kg: number;               // Maximum Takeoff Weight (kg)
  empty_weight_kg?: number;
  max_ground_speed_mps: number;  // Max speed limit (m/s)
  cruise_speed_mps: number;      // Nominal cruise speed (m/s)
  max_climb_rate_mps: number;    // Vertical ascent limit (m/s)
  max_descent_rate_mps: number;  // Vertical descent limit (m/s)
  max_turn_rate_deg_s: number;   // Maximum turn rate (deg/s)
  max_flight_time_min: number;   // Maximum endurance (minutes)
  battery_capacity_mah?: number;
}

export interface GeoPosition3D {
  latitude: number;       // degrees [-90, 90] WGS84
  longitude: number;      // degrees [-180, 180] WGS84
  altitude_m: number;     // meters
  altitude_reference: AltitudeReference;
}

export interface VelocityVector3D {
  ground_speed_mps: number;     // meters per second >= 0
  vertical_speed_mps?: number;  // meters per second (+ climbs, - descends), optional if not provided
  heading_deg: number;          // degrees [0, 360)
  air_speed_mps?: number;       // Airspeed if reported by pitot tube (m/s)
  drift_angle_deg?: number;     // Drift angle in degrees
}

/**
 * Standard Telemetry Message emitted by UAV or Simulator (Part 2)
 */
export interface UAVTelemetryMessage {
  schema_version: typeof SCHEMA_VERSION | string;
  type: 'uav.telemetry';
  sequence: number;                  // Sequence number (source_sequence or internal receive_sequence)
  timestamp: string;                 // ISO 8601 UTC - Simulator virtual clock time
  message_created_at?: string;       // ISO 8601 UTC - Wall clock when packet was generated at simulator
  simulation_id?: string;
  simulation_time_sec?: number;      // Relative simulation time (e.g. 71.2s from Phuoc)
  uav_id: string;                    // Unique identifier (e.g. UAV-01)
  callsign?: string;                 // Radio callsign (e.g. MED-EXPRESS-1)
  flight_plan_id?: string;           // Active plan ID or undefined if unlinked
  position: GeoPosition3D;           // Raw physical observation (EPSG:4326)
  velocity: VelocityVector3D;        // Physical velocity vector
  status: UAVFlightStatus;
  flight_mode?: string;              // Simulator-specific mode (e.g. AUTONOMOUS_UTM_CONTROL)
  battery_pct?: number;              // 0 - 100%
  rssi_dbm?: number;                 // Signal strength in dBm
  uav_profile?: UAVPerformanceProfile; // Performance specifications
  is_inferred_sequence?: boolean;    // True if sequence was generated by receiver, not source
  data_source_format?: 'INTERNAL_V1' | 'PHUOC_ASTM_F3411' | 'TEST_IMPORT';
}

/**
 * 4D Waypoint (3D Geodetic Coordinates + Planned Time Dimension)
 */
export interface Waypoint4D {
  id: string;
  name: string;
  latitude: number;
  longitude: number;
  altitude_m: number;
  planned_speed_mps: number;
  planned_time_utc: string;          // Planned arrival time ETA (ISO 8601 UTC)
  time_tolerance_s?: number;         // Permissible window around ETA (+/- seconds)
}

/**
 * Strategic 4D Flight Plan (Part 3 contract)
 */
export interface FlightPlan {
  plan_id: string;
  source?: 'UTM_OPS';
  altitude_reference?: AltitudeReference;
  departure_name?: string | null;
  destination_name?: string | null;
  uav_id: string;
  callsign: string;
  operator_id?: string;
  uav_profile?: UAVPerformanceProfile;
  departure_time_utc: string;
  estimated_arrival_time_utc: string;
  waypoints: Waypoint4D[];
  corridor_width_m: number;          // Horizontal safety corridor buffer radius (meters)
  altitude_corridor_m: number;       // Vertical safety corridor buffer (+/- meters)
  time_tolerance_s: number;          // 4D temporal corridor buffer (+/- seconds)
  color?: string;                    // Color hex for 3D trajectory rendering
  status: 'SCHEDULED' | 'ACTIVE' | 'COMPLETED' | 'CANCELLED';
}

export type RestrictedZoneType = 
  | 'NFZ_AIRPORT' 
  | 'MILITARY' 
  | 'CRITICAL_INFRASTRUCTURE' 
  | 'URBAN_POPULATION' 
  | 'WEATHER_HAZARD';

/**
 * 3D Restricted Airspace / Geofence Zone
 */
export interface RestrictedZone {
  zone_id: string;
  name: string;
  type: RestrictedZoneType;
  min_altitude_m: number;
  max_altitude_m: number;
  boundary: Array<{ latitude: number; longitude: number }>; // WGS84 polygon
  color?: string;                    // RGBA or Hex
  active: boolean;
  notes?: string;
}

/**
 * Weather & Environment State (Part 2 contract)
 */
export interface EnvironmentState {
  timestamp: string;
  wind_speed_mps: number;
  wind_direction_deg: number;
  gust_speed_mps?: number;
  temperature_c: number;
  visibility_km: number;
  precipitation_mm?: number;
  weather_condition: 'CLEAR' | 'CLOUDY' | 'RAIN' | 'HIGH_WIND' | 'FOG';
}

/**
 * Simulator Clock & State Message (Part 2 contract)
 */
export interface SimulationStatus {
  simulation_id: string;
  status: 'RUNNING' | 'PAUSED' | 'STOPPED';
  sim_time: string;                  // Simulation virtual clock (ISO 8601)
  playback_speed: number;            // 1.0 = real-time, 2.0 = 2x, 0.5 = half speed
  active_uav_count: number;
  timestamp: string;                 // Wall-clock timestamp from simulator engine
}

export type AlertSeverity = 'INFO' | 'WARNING' | 'CRITICAL';

export type AlertSource = 
  | 'TACTICAL_CONFLICT_PART5' 
  | 'STRATEGIC_DEVIATION' 
  | 'GEOFENCE_BREACH' 
  | 'DATA_LINK_LOSS' 
  | 'OUT_OF_SEQUENCE' 
  | 'WEATHER_WARNING' 
  | 'SYSTEM';

/**
 * Unified Monitoring Alert (from Part 4 internal checks or external Part 5 AI)
 */
export interface MonitoringAlert {
  alert_id: string;
  severity: AlertSeverity;
  source: AlertSource;
  uav_id?: string;
  target_uav_id?: string;            // In case of conflict between two UAVs
  title: string;
  description: string;
  timestamp: string;
  acknowledged: boolean;
  metrics?: {
    deviation_m?: number;
    time_deviation_s?: number;
    estimated_time_to_conflict_s?: number;
    distance_to_nfz_m?: number;
  };
}

/**
 * Command Acknowledgement from UTM / Part 2
 */
export interface CommandAcknowledgement {
  command_id: string;
  status: 'ACCEPTED' | 'REJECTED' | 'EXECUTING' | 'COMPLETED' | 'FAILED';
  message: string;
  timestamp: string;
}

/**
 * Union type for incoming raw WebSocket messages
 */
export type IngestibleMessage = 
  | UAVTelemetryMessage 
  | { type: 'simulation.status'; payload: SimulationStatus }
  | { type: 'environment.state'; payload: EnvironmentState }
  | { type: 'monitoring.alert'; payload: MonitoringAlert }
  | { type: 'flight_plan.update'; payload: FlightPlan }
  | { type: 'flight_plan.snapshot'; payload: FlightPlan[] }
  | { type: 'zone.update'; payload: RestrictedZone };
